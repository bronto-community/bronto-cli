// Command docgen generates the Mintlify command reference for the docs
// site from the live cobra tree (cli.NewRootCmd): one page per available
// top-level command (subcommands become sections on that page), an
// index.mdx overview table, global-flags.mdx, and navigation.json, the
// sidebar group that docs/cli/navigation.json pulls in with "$ref".
// `make docs-reference` runs it; `make docs-reference-check` regenerates
// and fails on any diff, so the committed reference can never drift from
// the binary.
//
// Output is deterministic: commands and flags are walked in cobra's sorted
// order, nothing time- or host-dependent is emitted, BRONTO_* environment
// variables are cleared before the tree is built, and any machine-specific
// string that still leaks into help text or flag defaults (home directory,
// temp dir, user config/cache dir) is replaced with a stable placeholder.
// (Bare host or user names are deliberately not replaced: a short name
// like "user" would also rewrite ordinary words, differently per machine.)
//
// "Learn more" links come from a hand-maintained YAML map (command path
// without the leading "bronto" -> a docs.bronto.io concept page and API
// reference page). An entry naming a command that does not exist fails
// the run, so the map cannot rot.
//
// Every page and the sidebar group carry a Lucide icon (docs.json sets
// "icons": {"library": "lucide"}, as the official docs do). commandIcons
// must name exactly the documented top-level commands, so a new command
// fails the run until it is given an icon.
//
// A command page's frontmatter description (the page's meta description
// for search engines) comes from pageDescriptions, falling back to the
// command's Short, which stays brief because --help shows it. An entry
// naming a command that is not a documented top-level command fails the
// run.
//
// It also writes the API coverage page (apicoverage.go): every operation
// in api/openapi.yaml and the command that calls it.
//
// Usage (from the repo root):
//
//	go run ./internal/tools/docgen [-out dir] [-links file] [-spec file] [-api-coverage file]
package main

