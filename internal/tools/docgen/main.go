// checkIcons fails unless commandIcons names exactly the documented
// top-level commands.
func checkIcons(root *cobra.Command) error {
	var bad []string
	seen := map[string]bool{}
	for _, c := range topLevel(root) {
		seen[c.Name()] = true
		if commandIcons[c.Name()] == "" {
			bad = append(bad, fmt.Sprintf("%q has no icon: add a Lucide icon name to commandIcons", c.Name()))
		}
	}
	for name := range commandIcons {
		if !seen[name] {
			bad = append(bad, fmt.Sprintf("commandIcons: %q is not a documented top-level command", name))
		}
	}
	if len(bad) > 0 {
		sort.Strings(bad)
		return fmt.Errorf("icons:\n  %s", strings.Join(bad, "\n  "))
	}
	return nil
}

