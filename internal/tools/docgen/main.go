const (
	defaultOut   = "docs/cli/reference/commands"
	defaultLinks = "docs/reference-links.yaml"
	// urlBase is where the generated pages are served on the site. Without
	// the slashes it is also the pages' path in docs.json navigation.
	urlBase         = "/cli/reference/commands/"
	globalFlagsSlug = "global-flags"
	// Icons of the pages that are not a command, and of the sidebar group.
	indexIcon       = "list"
	globalFlagsIcon = "flag"
	groupIcon       = "terminal"
	// Titles and descriptions of the pages that are not a command.
	indexTitle             = "bronto CLI command reference"
	indexDescription       = "Overview of every bronto CLI command, subcommand, and flag, generated from the bronto command tree so the reference always matches the CLI binary."
	globalFlagsTitle       = "bronto CLI global flags"
	globalFlagsDescription = "Flags accepted by every bronto CLI command, including --profile, --region, --output, --jq, --dry-run, and --api-key, plus root-only flags like --version."
	generatedNotice        = "{/* Generated by internal/tools/docgen from the cobra command tree. DO NOT EDIT: run `make docs-reference`. */}"
)

func main() {
	out := flag.String("out", defaultOut, "output directory for the generated pages")
	links := flag.String("links", defaultLinks, "YAML map of command path -> docs.bronto.io URL")
	spec := flag.String("spec", defaultSpec, "OpenAPI document for the API coverage page")
	apiCoverage := flag.String("api-coverage", defaultAPICoverage, "output file for the API coverage page")
	flag.Parse()
	err := run(*out, *links)
	if err == nil {
		err = writeAPICoverage(*spec, *apiCoverage)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}

func run(outDir, linksFile string) error {
	// Flag defaults and help text must not depend on the generating
	// machine's environment.
	for _, kv := range os.Environ() {
		if k, _, _ := strings.Cut(kv, "="); strings.HasPrefix(k, "BRONTO_") {
			_ = os.Unsetenv(k)
		}
	}

	root := cli.NewRootCmd()
	root.InitDefaultHelpFlag()
	root.InitDefaultVersionFlag()
	root.InitDefaultCompletionCmd()

	links, err := loadLinks(linksFile, root)
	if err != nil {
		return err
	}
	if err := checkIcons(root); err != nil {
		return err
	}
	if err := checkPageDescriptions(root); err != nil {
		return err
	}
	g := &gen{root: root, links: links, norm: newNormalizer()}

	if err := os.MkdirAll(outDir, 0o755); err != nil { //nolint:gosec // committed docs directory, world-readable by design
		return err
	}
	// Remove previously generated pages so a deleted command's page goes
	// away instead of lingering.
	old, err := filepath.Glob(filepath.Join(outDir, "*.md*"))
	if err != nil {
		return err
	}
	for _, f := range old {
		if err := os.Remove(f); err != nil {
			return err
		}
	}

	// Sidebar order: overview, global flags, then the commands A-Z.
	slugs := []string{"index", globalFlagsSlug}
	files := map[string]string{
		"index.mdx":              g.indexPage(),
		globalFlagsSlug + ".mdx": g.globalFlagsPage(),
	}
	for _, c := range topLevel(root) {
		slugs = append(slugs, c.Name())
		files[c.Name()+".mdx"] = g.commandPage(c)
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if err := os.WriteFile(filepath.Join(outDir, n), []byte(tidy(files[n])), 0o644); err != nil { //nolint:gosec // committed docs pages, world-readable by design
			return err
		}
	}
	nav, err := navigation(slugs)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(outDir, "navigation.json"), nav, 0o644); err != nil { //nolint:gosec // committed docs config, world-readable by design
		return err
	}
	fmt.Printf("docgen: wrote %d pages and navigation.json to %s\n", len(names), outDir)
	return nil
}

// navigation renders the sidebar group for the generated pages, in the
// docs.json format. Page paths are relative to the docs root (docs/).
func navigation(slugs []string) ([]byte, error) {
	base := strings.Trim(urlBase, "/")
	pages := make([]string, len(slugs))
	for i, s := range slugs {
		pages[i] = base + "/" + s
	}
	b, err := json.MarshalIndent(struct {
		Group string   `json:"group"`
		Icon  string   `json:"icon"`
		Pages []string `json:"pages"`
	}{"Commands", groupIcon, pages}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

var blankRuns = regexp.MustCompile(`\n{3,}`)

// tidy collapses runs of blank lines and ends the page with one newline.
func tidy(page string) string {
	return strings.TrimRight(blankRuns.ReplaceAllString(page, "\n\n"), "\n") + "\n"
}

// topLevel returns the root's documented commands in cobra's sorted order.
func topLevel(root *cobra.Command) []*cobra.Command {
	var cmds []*cobra.Command
	for _, c := range root.Commands() {
		if c.IsAvailableCommand() {
			cmds = append(cmds, c)
		}
	}
	return cmds
}

// subcommands returns c's documented subcommands in cobra's sorted order.
func subcommands(c *cobra.Command) []*cobra.Command {
	var cmds []*cobra.Command
	for _, s := range c.Commands() {
		if s.IsAvailableCommand() {
			cmds = append(cmds, s)
		}
	}
	return cmds
}

// relPath is a command's path without the leading root name, the key used
// by reference-links.yaml (e.g. "datasets parser").
func relPath(c *cobra.Command) string {
	return strings.TrimPrefix(strings.TrimPrefix(c.CommandPath(), c.Root().Name()), " ")
}

// learnMore is one command's entry in reference-links.yaml.
type learnMore struct {
	Docs string `yaml:"docs"` // platform concept page
	API  string `yaml:"api"`  // API reference page for the main endpoint
}

func loadLinks(file string, root *cobra.Command) (map[string]learnMore, error) {
	data, err := os.ReadFile(file) //nolint:gosec // path comes from the -links flag of a dev tool
	if err != nil {
		return nil, err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	links := map[string]learnMore{}
	if err := doc.Decode(&links); err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	var bad []string
	if len(doc.Content) == 1 {
		// Unknown keys under a command (a typo like "apy:") would
		// silently drop the link.
		for i := 1; i < len(doc.Content[0].Content); i += 2 {
			entry := doc.Content[0].Content[i]
			for j := 0; j < len(entry.Content); j += 2 {
				if key := entry.Content[j].Value; key != "docs" && key != "api" {
					bad = append(bad, fmt.Sprintf("%q: unknown key %q (want docs or api)", doc.Content[0].Content[i-1].Value, key))
				}
			}
		}
	}
	for k, v := range links {
		c, rest, err := root.Find(strings.Fields(k))
		if err != nil || c == root || len(rest) > 0 || relPath(c) != k || !c.IsAvailableCommand() {
			bad = append(bad, fmt.Sprintf("%q is not a documented command", k))
		}
		if v.Docs == "" && v.API == "" {
			bad = append(bad, fmt.Sprintf("%q: needs a docs or api link", k))
		}
		for _, u := range []string{v.Docs, v.API} {
			if u != "" && !strings.HasPrefix(u, "https://docs.bronto.io/") {
				bad = append(bad, fmt.Sprintf("%q: link %q must be a https://docs.bronto.io/ URL", k, u))
			}
		}
		if v.API != "" && !strings.HasPrefix(v.API, "https://docs.bronto.io/api-reference/") {
			bad = append(bad, fmt.Sprintf("%q: api link %q must be under https://docs.bronto.io/api-reference/", k, v.API))
		}
	}
	if len(bad) > 0 {
		sort.Strings(bad)
		return nil, fmt.Errorf("%s:\n  %s", file, strings.Join(bad, "\n  "))
	}
	return links, nil
}

